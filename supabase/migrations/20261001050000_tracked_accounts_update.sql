drop policy if exists "tracked_accounts_update_own" on public.project_tracked_accounts;

create policy "tracked_accounts_update_own"
  on public.project_tracked_accounts for update
  using (
    user_id = auth.uid()
    and exists (
      select 1 from public.projects p
      where p.id = project_id and p.owner_id = auth.uid()
    )
  )
  with check (
    user_id = auth.uid()
    and exists (
      select 1 from public.projects p
      where p.id = project_id and p.owner_id = auth.uid()
    )
  );
