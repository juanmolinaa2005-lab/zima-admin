function flagEmoji(code: string) {
  return [...code.toUpperCase()]
    .map((char) => String.fromCodePoint(0x1f1e6 - 65 + char.charCodeAt(0)))
    .join("");
}

export const LEGAL_COUNTRIES = RAW.map(([code, name]) => ({
  code,
  name,
  flag: flagEmoji(code),
})).sort((a, b) => a.name.localeCompare(b.name, "es"));

export function legalCountryByName(name: string) {
  const folded = name.trim().toLocaleLowerCase("es");
  return LEGAL_COUNTRIES.find((country) => country.name.toLocaleLowerCase("es") === folded) ?? null;
}
