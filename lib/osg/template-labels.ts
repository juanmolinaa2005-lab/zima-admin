export function normalizeTemplateTitle(raw: string) {
  return raw
    .toLowerCase()
    .replace(/store set/g, " ")
    .replace(/\bcopy\b/g, " ")
    .replace(/iphone[^a-z0-9]*.*$/g, " ")
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function labelForTemplate(raw: string): TemplateLabel {
  const key = normalizeTemplateTitle(raw);
  if (OSG_TEMPLATE_LABELS[key]) return OSG_TEMPLATE_LABELS[key];
  for (const [k, value] of Object.entries(OSG_TEMPLATE_LABELS)) {
    if (key.includes(k) || k.includes(key)) return value;
  }
  if (/blank|canvas|lienzo/.test(key)) return OSG_TEMPLATE_LABELS["blank canvas"];
  if (/capy/.test(key)) return OSG_TEMPLATE_LABELS.mycapy;
  if (/ludo/.test(key)) return OSG_TEMPLATE_LABELS["ludo wala"];
  const name = raw
    .replace(/\s*store set\s*/i, "")
    .replace(/\s*copy\s*/i, "")
    .replace(/\s*iPhone.*$/i, "")
    .trim();
  return {
    name: name || raw,
    desc: "Set de capturas listo para personalizar.",
  };
}
