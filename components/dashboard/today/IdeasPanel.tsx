"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import { FORMAT_LABEL, type ContentIdea } from "@/lib/ideas/types";

const PLATFORM_LABEL: Record<string, string> = {
  tiktok: "TikTok",
  instagram: "Instagram",
  youtube: "YouTube",
  linkedin: "LinkedIn",
  x: "X",
};

const VISIBLE = 3;

function scriptOf(idea: ContentIdea): string {
  return [idea.hook, "", ...idea.beats.map((b) => `• ${b}`), idea.caption ? `\n${idea.caption}` : "", idea.hashtags.join(" ")]
    .filter((line) => line !== undefined)
    .join("\n")
    .trim();
}

function IdeaCard({
  idea,
  onStatus,
  onCreate,
}: {
  idea: ContentIdea;
  onStatus: (status: "used" | "discarded") => void;
  onCreate: () => void;
}) {
  const [open, setOpen] = useState(false);
  const [copied, setCopied] = useState(false);

  async function copy() {
    await navigator.clipboard.writeText(scriptOf(idea)).catch(() => undefined);
    setCopied(true);
    window.setTimeout(() => setCopied(false), 1400);
  }

  const beats = open ? idea.beats : idea.beats.slice(0, 2);
  return (
    <article className="ui-lift flex flex-col rounded-xl border border-[var(--border)] bg-white p-4">
      <div className="flex items-center gap-2 text-[12px] text-[var(--muted)]">
        <span className="rounded-full bg-[var(--surface-alt)] px-2 py-0.5 font-medium text-[var(--foreground)]">{FORMAT_LABEL[idea.format] ?? idea.format}</span>
        {idea.platform ? <span>{PLATFORM_LABEL[idea.platform] ?? idea.platform}</span> : null}
        <button
          type="button"
          onClick={() => onStatus("discarded")}
          aria-label="Descartar idea"
          title="Descartar"
          className="ml-auto rounded-md p-1 text-[var(--muted-soft)] transition hover:bg-[var(--surface-alt)] hover:text-[var(--foreground)]"
        >
          <svg viewBox="0 0 16 16" className="h-3.5 w-3.5" fill="none" aria-hidden>
            <path d="m4 4 8 8M12 4l-8 8" stroke="currentColor" strokeWidth="1.6" strokeLinecap="round" />
          </svg>
        </button>
      </div>
      {idea.variant_of ? <p className="mt-2 line-clamp-1 text-[12px] text-[var(--muted)]">Variante de “{idea.variant_of}”</p> : null}
      <p className="mt-2 text-[16px] font-semibold leading-snug text-[var(--foreground)]">{idea.hook}</p>
      <ul className="mt-3 flex-1 space-y-1 text-[13px] leading-snug text-[var(--muted)]">
        {beats.map((b) => (
          <li key={b} className="flex gap-2">
            <span aria-hidden className="mt-[7px] h-1 w-1 shrink-0 rounded-full bg-[var(--muted-soft)]" />
            {b}
          </li>
        ))}
      </ul>
      {idea.beats.length > 2 ? (
        <button type="button" onClick={() => setOpen((v) => !v)} className="mt-1 self-start text-[12px] font-medium text-[var(--muted)] hover:text-[var(--foreground)]">
          {open ? "Ver menos" : "Ver guion completo"}
        </button>
      ) : null}
      <div className="mt-4 flex flex-wrap gap-2">
        <button
          type="button"
          onClick={() => void copy()}
          className="ui-press rounded-lg border border-[var(--border)] px-3 py-1.5 text-[13px] font-medium text-[var(--foreground)] transition hover:border-[var(--foreground)]"
        >
          {copied ? "Copiado ✓" : "Copiar guion"}
        </button>
        {idea.format !== "founder-post" ? (
          <button
            type="button"
            onClick={() => {
              void copy();
              onCreate();
            }}
            className="ui-press rounded-lg border border-[var(--border)] px-3 py-1.5 text-[13px] font-medium text-[var(--foreground)] transition hover:border-[var(--foreground)]"
          >
            Crear video
          </button>
        ) : null}
        <button
          type="button"
          onClick={() => onStatus("used")}
          className="ui-press ml-auto rounded-lg bg-[var(--foreground)] px-3 py-1.5 text-[13px] font-medium text-white transition hover:opacity-85"
        >
          Publicado
        </button>
      </div>
    </article>
  );
}

export function IdeasPanel({
  projectId,
  variantOf,
  onCreate,
}: {
  projectId: string;
  variantOf: { title: string; nonce: number } | null;
  onCreate: () => void;
}) {
  const [ideas, setIdeas] = useState<ContentIdea[] | null>(null);
  const [usedThisWeek, setUsedThisWeek] = useState(0);
  const [ai, setAi] = useState(false);
  const [busy, setBusy] = useState(false);
  const [showAll, setShowAll] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const autoGenerated = useRef(false);

  const generate = useCallback(
    async (opts: { count?: number; variantOf?: string } = {}) => {
      setBusy(true);
      setError(null);
      try {
        const res = await fetch(`/api/projects/${projectId}/ideas`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ count: opts.count ?? 3, variantOf: opts.variantOf }),
        });
        const json = (await res.json()) as { ideas?: ContentIdea[]; error?: string };
        if (!res.ok) throw new Error(json.error || "No se pudieron generar ideas");
        setIdeas((prev) => [...(json.ideas ?? []), ...(prev ?? [])]);
      } catch (err) {
        setError(err instanceof Error ? err.message : "No se pudieron generar ideas");
      } finally {
        setBusy(false);
      }
    },
    [projectId]
  );

  useEffect(() => {
    let alive = true;
    void (async () => {
      const res = await fetch(`/api/projects/${projectId}/ideas`, { cache: "no-store" }).catch(() => null);
      const json = res && res.ok ? ((await res.json()) as { ideas: ContentIdea[]; usedThisWeek: number; ai: boolean }) : null;
      if (!alive) return;
      setIdeas(json?.ideas ?? []);
      setUsedThisWeek(json?.usedThisWeek ?? 0);
      setAi(Boolean(json?.ai));
      if (json && json.ideas.length === 0 && !autoGenerated.current) {
        autoGenerated.current = true;
        void generate();
      }
    })();
    return () => {
      alive = false;
    };
  }, [projectId, generate]);

  const lastVariant = useRef<number | null>(null);
  useEffect(() => {
    if (!variantOf || lastVariant.current === variantOf.nonce) return;
    lastVariant.current = variantOf.nonce;
    void generate({ count: 3, variantOf: variantOf.title });
  }, [variantOf, generate]);

  function setStatus(idea: ContentIdea, status: "used" | "discarded") {
    const remaining = (ideas ?? []).filter((i) => i.id !== idea.id);
    setIdeas(remaining);
    if (status === "used") setUsedThisWeek((n) => n + 1);
    void fetch(`/api/projects/${projectId}/ideas`, {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ id: idea.id, status }),
    });
    if (remaining.length < VISIBLE && !busy) void generate({ count: VISIBLE - remaining.length });
  }

  const visible = showAll ? ideas ?? [] : (ideas ?? []).slice(0, VISIBLE);
  const hidden = (ideas?.length ?? 0) - visible.length;

  return (
    <section id="ideas-hoy" className="mt-8 scroll-mt-6">
      <div className="flex flex-wrap items-baseline justify-between gap-2">
        <div>
          <h2 className="text-[13px] font-semibold uppercase tracking-wide text-[var(--muted)]">Para publicar hoy</h2>
          <p className="mt-1 text-[13px] text-[var(--muted)]">
            <span className="tabular-nums font-medium text-[var(--foreground)]">{usedThisWeek}</span> publicados esta semana · la meta es 2–3 al día por cuenta
          </p>
        </div>
        <div className="flex items-center gap-3 text-[13px]">
          {ai ? (
            <span className="rounded-full bg-[var(--surface-alt)] px-2 py-0.5 text-[12px] font-medium text-[var(--foreground)]">Con IA</span>
          ) : (
            <a href={`/projects/${projectId}/settings/api`} className="text-[var(--muted)] hover:text-[var(--foreground)]">
              Conecta OpenAI para ideas a tu medida
            </a>
          )}
          <button
            type="button"
            onClick={() => void generate()}
            disabled={busy}
            className="ui-press rounded-lg border border-[var(--border)] bg-white px-3 py-1.5 font-medium text-[var(--foreground)] transition hover:border-[var(--foreground)] disabled:opacity-50"
          >
            {busy ? "Pensando…" : "Más ideas"}
          </button>
        </div>
      </div>

      {error ? <p className="mt-3 text-[13px] text-red-600">{error}</p> : null}

      <div className="ui-stagger mt-3 grid gap-3 md:grid-cols-3">
        {ideas === null || (ideas.length === 0 && busy)
          ? [0, 1, 2].map((i) => <div key={i} className="ui-skeleton h-[230px] rounded-xl" />)
          : visible.map((idea) => <IdeaCard key={idea.id} idea={idea} onStatus={(s) => setStatus(idea, s)} onCreate={onCreate} />)}
      </div>

      {hidden > 0 ? (
        <button type="button" onClick={() => setShowAll(true)} className="mt-3 text-[13px] font-medium text-[var(--muted)] hover:text-[var(--foreground)]">
          Ver {hidden} más
        </button>
      ) : null}
    </section>
  );
}
